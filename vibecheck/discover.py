"""Find the files that belong to a project, skipping build output, vendored
libraries and generated code, which say nothing about how the project was
written."""

from __future__ import annotations

import fnmatch
import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from vibecheck.cpp import SOURCE_EXTS, SourceFile

MAX_SOURCE_BYTES = 512 * 1024

SKIP_DIRS = {
    ".git", ".hg", ".svn", ".cache", ".vscode", ".idea", ".direnv", "__pycache__",
    "node_modules", "_deps", "build", "builds", "out", "bin", "obj", "dist", "target",
    "result", "Debug", "Release", "x64", "CMakeFiles",
    # vendored code
    "third_party", "third-party", "thirdparty", "3rdparty", "external", "extern",
    "vendor", "vendored", "deps", "subprojects", "imgui", "glad", "glfw", "googletest",
    "gtest", "catch2", "Catch2", "doctest", "fmt", "spdlog", "eigen", "boost", "nlohmann",
}
SKIP_DIR_PATTERNS = ("build-*", "build_*", "cmake-build-*", "*.dSYM")
VENDORED_FILES = (
    "stb_*.h", "json.hpp", "catch.hpp", "catch_amalgamated.*", "doctest.h", "miniaudio.h",
    "sqlite3.c", "sqlite3.h", "sqlite3ext.h", "glad.c", "glad.h", "khrplatform.h",
    "httplib.h", "CLI11.hpp", "cxxopts.hpp", "argparse.hpp", "toml.hpp", "tinyxml2.*",
    "lodepng.*", "cJSON.*", "linenoise.*", "utest.h", "unity.c", "unity.h",
    "unity_internals.h", "greatest.h", "munit.*", "miniz.*", "dr_*.h", "tinyobjloader.*",
    "tiny_obj_loader.h", "imgui*.cpp", "imgui*.h", "imstb_*.h", "nuklear.h", "raygui.h",
    "uthash.h", "utlist.h", "sokol_*.h", "cgltf.h", "volk.*", "vk_mem_alloc.h",
)
GENERATED = re.compile(r"generated by|auto-?generated|do not edit|@generated", re.I)
IGNORE_FILE = ".vibecheckignore"


@dataclass
class Project:
    root: Path
    files: list[str]  # every file considered part of the project (relative posix)
    sources: list[SourceFile] = field(default_factory=list)
    git: bool = False
    skipped_sources: list[str] = field(default_factory=list)
    commit_count: int = 0  # filled in by the git collector

    @property
    def loc(self) -> int:
        return sum(s.loc for s in self.sources)

    @property
    def kloc(self) -> float:
        return self.loc / 1000


def _dir_skipped(part: str) -> bool:
    return part in SKIP_DIRS or any(fnmatch.fnmatch(part, p) for p in SKIP_DIR_PATTERNS)


def is_vendored_file(path: str) -> bool:
    name = PurePosixPath(path).name
    return any(fnmatch.fnmatch(name, p) for p in VENDORED_FILES)


def is_excluded_path(path: str) -> bool:
    """True for paths inside build output or vendored directories."""
    parts = PurePosixPath(path).parts[:-1]
    return any(_dir_skipped(p) for p in parts)


def _load_patterns(root: Path, extra: tuple[str, ...]) -> list[str]:
    patterns = list(extra)
    try:
        for raw in (root / IGNORE_FILE).read_text().splitlines():
            raw = raw.strip()
            if raw and not raw.startswith("#"):
                patterns.append(raw)
    except OSError:
        pass
    return patterns


def _matches(path: str, patterns: list[str]) -> bool:
    for p in patterns:
        p = p.rstrip("/")
        if fnmatch.fnmatch(path, p) or fnmatch.fnmatch(path, p + "/*"):
            return True
        if "/" not in p and any(fnmatch.fnmatch(part, p) for part in PurePosixPath(path).parts):
            return True
    return False


def git_toplevel(root: Path) -> Path | None:
    try:
        r = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return Path(r.stdout.strip()) if r.returncode == 0 else None


def _git_files(root: Path) -> list[str] | None:
    try:
        r = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True, timeout=60,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode != 0:
        return None
    files = []
    for raw in r.stdout.split(b"\0"):
        if raw:
            rel = raw.decode("utf-8", "replace")
            if (root / rel).is_file():  # skips deleted files and submodules
                files.append(rel)
    return files


def _walk_files(root: Path) -> list[str]:
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and not _dir_skipped(d))
        rel_dir = Path(dirpath).relative_to(root)
        for name in sorted(filenames):
            files.append((rel_dir / name).as_posix())
    return files


def load_project(root: Path, use_git: bool = True, exclude: tuple[str, ...] = ()) -> Project:
    root = root.resolve()
    tracked = _git_files(root) if use_git and git_toplevel(root) else None
    git = tracked is not None
    listed = tracked if git else _walk_files(root)

    patterns = _load_patterns(root, exclude)
    files = sorted(f for f in listed if not is_excluded_path(f) and not _matches(f, patterns))

    project = Project(root=root, files=files, git=git)
    for rel in files:
        if PurePosixPath(rel).suffix.lower() not in SOURCE_EXTS:
            continue
        if is_vendored_file(rel):
            project.skipped_sources.append(rel)
            continue
        path = root / rel
        try:
            if path.stat().st_size > MAX_SOURCE_BYTES:
                project.skipped_sources.append(rel)
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if GENERATED.search(text[:1500]):
            project.skipped_sources.append(rel)
            continue
        project.sources.append(SourceFile.parse(rel, text.replace("\r\n", "\n")))
    return project
